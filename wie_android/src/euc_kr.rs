/// `text` as the game's font reads it — EUC-KR, ASCII letters uppercased (the font has no lowercase glyphs).
/// `None` when a character is outside what the font can draw (a syllable off KS X 1001, any other non-ASCII).
pub fn h2_euc_kr(text: &str) -> Option<Vec<u8>> {
    let mut out = Vec::with_capacity(text.len());
    for c in text.chars() {
        let cp = c as u32;
        if (0x20..=0x7e).contains(&cp) {
            out.push(c.to_ascii_uppercase() as u8);
        } else if (0xac00..=0xd7a3).contains(&cp) {
            let i = (cp - 0xac00) as usize;
            if KSX1001_SYLLABLE_BITS[i >> 3] >> (i & 7) & 1 == 0 {
                return None;
            }
            let rank: u32 = KSX1001_SYLLABLE_BITS[..i >> 3].iter().map(|b| b.count_ones()).sum::<u32>()
                + (KSX1001_SYLLABLE_BITS[i >> 3] & ((1u8 << (i & 7)) - 1)).count_ones();
            out.push(0xb0 + (rank / 94) as u8);
            out.push(0xa1 + (rank % 94) as u8);
        } else {
            return None;
        }
    }
    Some(out)
}

